#!/usr/bin/env python3
"""
Generate the FUSS-standalone test of the coupled ablating wall BC 307 (plan 08 sections 2.5 ii and 3.5 ii, stage D).

Two runs of ONE problem, the base ../../darcy/ATC2-chemistryOff-type2 (TACOT, type 2, 100 graded cells; its 60 s run is
.slow, so these run 1 s): face 2 is the ablating wall under ATC 2.1's heating values, through two input paths.

  run307/  face 2 typed 307: line 2 = the 103 connectivity record `1 1 1 1 1 1 0 0 1` (read, never resolved
           standalone) + `T_inf B'-file`; no lambda (a coupled face runs at lambda = 0); the exchange values come from
           the TEST ONLY key [FUSS-Ablation] coupled-env-file = env307.dat (t p_w rhoeUeCH h_r q_rad).
  run306/  face 2 typed 306: line 2 = `0.0, 300.0, bprime_tacot_earth.dat, env306.dat` (lambda = 0), env306.dat =
           the same values with chem = 1, hconv = 0, T_edge = 300 (t p_w rhoeUeCH0 h_r q_rad chem hconv T_edge).

One input.ini, mesh, table set, probe list and output cadence; the runs differ only in the face-2 records, the env file
and the coupled-env-file line, so nothing but the input path can move a byte. Both use law = static (a 307 face never
recedes; a static 306 face consumes no char). verify.py compares every field file, seb.txt, wall.tec and
bc306-state.dat. Run from this directory; it rewrites run307/ and run306/.
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, "..", "..", "darcy", "ATC2-chemistryOff-type2"))
TABLE = os.path.abspath(os.path.join(HERE, "..", "tables", "bprime_tacot_earth.dat"))
ENV_HEAD = "// t p_w rhoeUeCH0 h_r q_rad chem hconv T_edge   (SI; plan 08 section 2.1, linear in t, clamped)"
COUPLED_HEAD = "// t p_w rhoeUeCH h_r q_rad   (SI; TEST ONLY exchange values of a 307 face, linear in t, clamped)"
ROWS = [(0.0, 101325.0, 0.3, 1.5e6, 0.0), (60.0, 101325.0, 0.3, 1.5e6, 0.0)]   # ATC 2.1's heating values
LINE307 = "     1 1 1 1 1 1 0 0 1  300.0, bprime_tacot_earth.dat"
LINE306 = "     0.0, 300.0, bprime_tacot_earth.dat, env306.dat"

HEADER = """; =============================================================================
;  The coupled ablating wall BC 307 standalone (plan 08 sections 2.5 ii, 3.5 ii): run307/ and run306/ solve ONE
;  problem through two input paths -- the 307 exchange values from the TEST ONLY coupled-env-file, the same values
;  as a 306 env table with lambda 0 -- and must agree byte for byte.
;
;  Generated by ../generate.py -- edit that, not this.
; =============================================================================
"""


def fmt(v):
    return repr(float(v))


def write_rows(path, head, rows):
    with open(path, "w") as fh:
        fh.write(head + "\n")
        for r in rows:
            fh.write(" ".join(fmt(v) for v in r) + "\n")


def ini_body():
    s = open(os.path.join(BASE, "input.ini")).read()
    body = s[s.index("[FUSS-Parameters]"):]
    body = body.replace("time-threshold = 60.0", "time-threshold = 1.0")
    body = body.replace("sol-dtime     = 10.0", "sol-dtime     = 0.25")
    assert "time-threshold = 1.0" in body and "sol-dtime     = 0.25" in body
    return body


def main():
    body = ini_body()
    for run, typ in (("run307", "307"), ("run306", "306")):
        d = os.path.join(HERE, run)
        if os.path.isdir(d):
            shutil.rmtree(d)
        os.makedirs(d)
        shutil.copytree(os.path.join(BASE, "INPUT"), os.path.join(d, "INPUT"))
        shutil.copytree(os.path.join(BASE, "MESH"), os.path.join(d, "MESH"))
        shutil.copy(TABLE, os.path.join(d, "INPUT", "bprime_tacot_earth.dat"))
        # face 2 (both j records): 303 -> 307 / 306 with the new line 2
        p = os.path.join(d, "INPUT", "bc.txt")
        lines = open(p).read().split("\n")
        out, i, n = [], 0, 0
        while i < len(lines):
            t = lines[i].split()
            if len(t) == 6 and t[4] == "2" and t[5] == "303":
                out.append(lines[i][:-3] + typ)
                out.append(LINE307 if typ == "307" else LINE306)
                i += 2
                n += 1
                continue
            out.append(lines[i])
            i += 1
        assert n == 2, n
        open(p, "w").write("\n".join(out))
        if typ == "307":
            write_rows(os.path.join(d, "INPUT", "env307.dat"), COUPLED_HEAD, ROWS)
            extra = "\n[FUSS-Ablation]\ncoupled-env-file = env307.dat\n"
        else:
            write_rows(os.path.join(d, "INPUT", "env306.dat"), ENV_HEAD,
                       [r + (1.0, 0.0, 300.0) for r in ROWS])
            extra = "\n[FUSS-Ablation]\n"
        open(os.path.join(d, "input.ini"), "w").write(HEADER + "\n" + body.rstrip("\n") + "\n" + extra)
        sh = open(os.path.join(BASE, "FUSS.sh")).read()
        assert "MASTERDIR=../../../.." in sh
        open(os.path.join(d, "FUSS.sh"), "w").write(sh.replace("MASTERDIR=../../../..", "MASTERDIR=../../../../..", 1))
        os.chmod(os.path.join(d, "FUSS.sh"), 0o755)
    print("coupled307: run307/ (BC 307 + coupled-env-file) and run306/ (BC 306, lambda 0) written")


if __name__ == "__main__":
    main()
