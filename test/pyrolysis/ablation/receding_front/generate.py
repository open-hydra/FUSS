#!/usr/bin/env python3
"""
Generate the receding-front exact case (plan 12 section D, P-D3's exact case): a receding ablating wall (BC 306) must
sweep out the WALL state (T_w), not the cell's.

A constant-property solid line (the --isothermal test tables of ../../exact/tables: cp 1000, h = 1000 (T - 298.15),
k 0.4, rho_v 280; the TACOT kinetics frozen, A = 0, so chi stays 0 while the reactive masses are carried) of
L = 0.1 m in 200 uniform cells recedes at the TEST ONLY sdot-override of 1/700 m/s (law nodeshift) under a constant
absorbed flux q = 4e5 W/m2 (env q_rad, emissivity 0, absorptivity 1, chemistry and convection off); face 1, the
pinned back, is adiabatic (301). In the surface frame the steady state is T = T_inf + (q/(rho c sdot)) exp(-sdot xi/a):
the wall reaches T_w* = T_inf + q/(rho c sdot) = 1300 K whatever k (the heat in raises the incoming solid from T_inf to
the temperature it leaves at). A remap that sweeps the cell state instead leaves the wall about 200 K hotter.
T(0) is that profile at the cell centres (it cuts the transient); 280 steps reach t* = sdot^2 t / a = 14.9.

  front/        the case above (type 1), the gate's primary: T_w against 1300 K, the per-step sweep identity, the
                budgets, a numpy replica of the discrete scheme (verify.py)
  twin_pyro/    the same with a Robin wall instead of the flux, hconv 400 W/m2/K to T_edge 2300 K (T_w* is again
                1300 K): the pyrolysis remap, which sweeps the wall state
  twin_legacy/  twin_pyro WITHOUT [FUSS-Pyrolysis] (a legacy properties.dat, rho 280, cp 1000, k 0.4): the legacy
                remap, which sweeps the wall state too since plan 12 U19 (before, the cell's own h: +9.0e-2 of the
                rise); verify.py holds it to T_w* as twin_pyro
  t2/           front under the type-2 closure (K = 1e-12 m2, p-init = p_w = 101325 Pa), 20 steps with a field file
                each: the swept energy and stored gas follow the wall state (T_w, p_w) step by step

Run from this directory; it rewrites the four case directories.
"""
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.abspath(os.path.join(HERE, "..", "..", "tools"))
TABLES = os.path.abspath(os.path.join(HERE, "..", "..", "exact", "tables"))
sys.path.insert(0, TOOLS)
import make_case as mc  # noqa: E402

NX, L = 200, 0.1
K_COND, RHO_V, CP = 0.4, 280.0, 1000.0
ALPHA = K_COND / (RHO_V * CP)          # 1/700000 m2/s
SDOT = 1.0 / 700.0                     # m/s: delta_p = ALPHA/SDOT = 1 mm, L = 100 delta_p
DELTA_P = 1.0e-3
Q = 4.0e5                              # W/m2
TINF = 300.0
DT_IC = 1000.0                         # T_w* - T_inf = Q / (RHO_V CP SDOT)
HCONV, TEDGE = 400.0, 2300.0           # the twins' Robin wall: (h T_edge + rho c sdot T_inf)/(h + rho c sdot) = 1300 K
PW = 101325.0
STEPS, STEPS_T2 = 280, 20
DEPTH = 5                              # test/pyrolysis/ablation/receding_front/<case> -> the repository root
LINE306 = "     0.0, %s, none, %s"

INI = """; =============================================================================
;  %(title)s
;  (plan 12 section D, P-D3's exact case)
;
%(body)s
;
;  Generated by ../generate.py -- edit that, not this.
; =============================================================================

[FUSS-Parameters]
newrun = true
res-threshold = 1e-30
time-threshold = 1e30
iter-threshold = %(steps)d

[FUSS-Numerics]
time-scheme = RK3
vnn = 0.5
time-accurate = true
integration-variables = cons
irs = false
%(pyro)s
[FUSS-MeshMotion]
law = nodeshift

[FUSS-Ablation]
sdot-override = %(sdot)s

[FUSS-IO]
sol-diter     = 1
sol-overwrite = %(overwrite)s
sol-format    = tecplot ascii
ini-diter     = 100000000
"""

PYRO1 = """
[FUSS-Pyrolysis]
gas-closure = type1
outflow-direction = +i
p-gas = 101325.0
"""
PYRO2 = """
[FUSS-Pyrolysis]
gas-closure = type2

[FUSS-Darcy]
solver = tridiag
tol = 1e-08
p-init = 101325.0
p-wall = 101325.0
"""

CASES = {
    "front": dict(title="Receding front under a constant absorbed flux: T_w* = T_inf + q/(rho c sdot) = 1300 K",
                  body=("A 0.1 m line of 200 cells (constant properties, kinetics frozen) recedes at 1/700 m/s under\n"
                        "q_rad = 4e5 W/m2 (absorptivity 1, emissivity 0); 280 steps, a field file and seb.txt row a step."),
                  env=(0.0, 0.0, Q), pyro=PYRO1, steps=STEPS, overwrite="true"),
    "twin_pyro": dict(title="Receding front, Robin wall, pyrolysis remap (sweeps the wall state)",
                      body=("front with hconv 400 W/m2/K to T_edge 2300 K instead of the flux (T_w* again 1300 K):\n"
                            "the pyrolysis remap sweeps T_w."),
                      env=(HCONV, TEDGE, 0.0), pyro=PYRO1, steps=STEPS, overwrite="true"),
    "twin_legacy": dict(title="Receding front, Robin wall, legacy remap (sweeps the wall state)",
                        body=("twin_pyro without [FUSS-Pyrolysis] (legacy properties.dat): the legacy remap sweeps\n"
                              "T_w too (plan 12 U19; sweeping the cell's own h, T_w missed 1300 K by about 9 percent)."),
                        env=(HCONV, TEDGE, 0.0), pyro="", steps=STEPS, overwrite="true"),
    "t2": dict(title="Receding front, type-2 closure: the swept energy and gas follow (T_w, p_w)",
               body=("front under the type-2 closure, K = 1e-12 m2, p-init = p_w = 101325 Pa; 20 steps with a\n"
                     "field file each (the surface cell's eta_st per step)."),
               env=(0.0, 0.0, Q), pyro=PYRO2, steps=STEPS_T2, overwrite="false"),
}


def nodes():
    xs = [L * i / NX for i in range(NX + 1)]
    xs[0], xs[-1] = 0.0, L
    return xs


def ic_profile(xs):
    """The continuum profile at the cell centres: T_inf + 1000 exp(-(L - x)/delta_p)."""
    import math
    return [TINF + DT_IC * math.exp(-(L - 0.5 * (xs[i] + xs[i + 1])) / DELTA_P) for i in range(NX)]


def write_ic_profile(path, xs, temps):
    """mc.write_ic with a T per cell (the same T on every j line)."""
    ni, nj, nk = len(xs), mc.NY + 1, mc.NK + 1
    lines = [' VARIABLES ="x" "y" "z" T matID',
             " ZONE  T = B1-SP, I=%d, J=%d, K=%d, DATAPACKING=BLOCK, VARLOCATION=([1-3]=NODAL,[4-5]=CELLCENTERED),"
             " SOLUTIONTIME=0.000000000000000E+000, STRANDID = 0" % (ni, nj, nk)]
    ys = [mc.DY * j for j in range(nj)]
    zs = [mc.DZ * k for k in range(nk)]
    for axis in range(3):
        for k in range(nk):
            for j in range(nj):
                for i in range(ni):
                    lines.append(mc.fmt((xs[i], ys[j], zs[k])[axis]))
    for k in range(mc.NK):
        for j in range(mc.NY):
            for i in range(NX):
                lines.append(mc.fmt(temps[i]))
    lines += [mc.fmt(1.0)] * (NX * mc.NY * mc.NK)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def freeze_kinetics(path):
    """A[2][r] 0 for every reaction (Load_Pyrolysis refuses only A < 0): chi stays 0, the masses are carried."""
    out, n = [], 0
    with open(path) as fh:
        for line in fh:
            m = re.match(r"^(A\[\d+\]\[\d+\])\s+\S+", line)
            if m:
                line = "%s 0\n" % m.group(1)
                n += 1
            out.append(line)
    if n == 0:
        mc.die("%s: no A[i][r] line to freeze" % path)
    out.insert(0, "// receding_front/generate.py: every A[i][r] set to 0 (frozen kinetics, chi = 0)\n")
    with open(path, "w") as fh:
        fh.write("".join(out))
    return n


def set_optics(path, eps, ab):
    """The emissivity and absorptivity columns (7 and 8 of 8) of a FUSS pyrolysis table, as mc.zero_optics."""
    out, n = [], 0
    with open(path) as fh:
        for line in fh:
            toks = line.split()
            try:
                [float(t) for t in toks]
                is_row = len(toks) == 8
            except ValueError:
                is_row = False
            if is_row:
                parts = line.rstrip("\n").split(" ")
                if len(parts) != 8:
                    mc.die("%s: a data row not separated by single blanks" % path)
                parts[6], parts[7] = "%.9E" % eps, "%.9E" % ab
                line = " ".join(parts) + "\n"
                n += 1
            out.append(line)
    if n == 0:
        mc.die("%s: no 8-column rows" % path)
    with open(path, "w") as fh:
        fh.write("".join(out))


def build(name, cfg, xs, temps):
    case = os.path.join(HERE, name)
    if os.path.isdir(case):
        shutil.rmtree(case)
    os.makedirs(os.path.join(case, "INPUT"))
    os.makedirs(os.path.join(case, "MESH"))
    inp = os.path.join(case, "INPUT")
    for f in mc.TABLE_FILES:
        shutil.copy(os.path.join(TABLES, f), os.path.join(inp, f))
    nfrozen = freeze_kinetics(os.path.join(inp, "pyrolysis.dat"))
    for f in ("virgin.dat", "char.dat"):
        set_optics(os.path.join(inp, f), 0.0, 1.0)
    if name == "t2":
        mc.set_permeability(os.path.join(inp, "pyrolysis.dat"), 1.0e-12)
    virgin = mc.read_table_zone1(os.path.join(inp, "virgin.dat"), 7)
    if any(v[0] != CP or v[2] != K_COND for v in virgin.values()):
        mc.die("the tables of %s are not the constant-property --isothermal set" % TABLES)
    write_ic_profile(os.path.join(inp, "ic.tec"), xs, temps)
    mc.write_ic(os.path.join(case, "MESH", "mesh.tec"), xs, "Block1", False, TINF)
    hconv, tedge, qrad = cfg["env"]
    env = "env_front.dat"
    mc.write_env_file(os.path.join(inp, env), [(0.0, PW, 0.0, 0.0, qrad, 0.0, hconv, tedge if hconv > 0 else TINF),
                                               (1.0e6, PW, 0.0, 0.0, qrad, 0.0, hconv, tedge if hconv > 0 else TINF)])
    nrec = mc.write_bc(os.path.join(inp, "bc.txt"), NX, (301, mc.VAL_FMT % 0.0), (306, LINE306 % (repr(TINF), env)))
    with open(os.path.join(inp, "phase.txt"), "w") as fh:
        fh.write("solid phase\nTACOT 1\n")
    mc.write_properties_dat(os.path.join(inp, "properties.dat"), "TACOT", virgin, RHO_V)
    if not cfg["pyro"]:
        for f in mc.TABLE_FILES:
            os.remove(os.path.join(inp, f))
    with open(os.path.join(case, "input.ini"), "w") as fh:
        fh.write(INI % dict(title=cfg["title"], body="\n".join(";  " + s for s in cfg["body"].split("\n")),
                            steps=cfg["steps"], pyro=cfg["pyro"], sdot=repr(SDOT), overwrite=cfg["overwrite"]))
    mc.write_fuss_sh(os.path.join(case, "FUSS.sh"), mc.DONOR_FUSS_SH, DEPTH)
    return nrec, nfrozen


def main():
    xs = nodes()
    temps = ic_profile(xs)
    for name, cfg in CASES.items():
        nrec, nfrozen = build(name, cfg, xs, temps)
        print("receding_front/%-12s %d bc records, %d cells, surface cell T(0) %.6f K%s"
              % (name, nrec, NX * mc.NY, temps[-1], "" if cfg["pyro"] else " (legacy: no pyrolysis tables)"))
    print("T_w* = %.6f K; delta_p = %.6e m; Pe = sdot dx / a = %.3f" % (TINF + Q / (RHO_V * CP * SDOT), ALPHA / SDOT,
                                                                       SDOT * (L / NX) / ALPHA))


if __name__ == "__main__":
    main()
