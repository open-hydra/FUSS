#!/usr/bin/env python3
"""
Generate the wall-smoothing demonstration (plan 08 sections 2.6 and 3.6, stage D): w1/ and w5/, one problem run with
[FUSS-Ablation] smoothing-width = 1 (off) and 5 (thesis Eq. 5.1).

A 2-D TACOT slab under the type-2 closure, 0.2 m wide x 0.05 m deep, 40 x 20 uniform cells (a top face is 5 mm), one
block: the top face (face 4) is the ablating wall BC 306 with ATC 2.2's heating rows (chem = 1, h_r = 1.5e6, the
equilibrium B' table of ../tables), law = nodeshift, 20 s; the sides are symmetry planes (300), the bottom adiabatic
(301), the k faces null (2-D). rho_e u_e C_H0 varies along the wall with period FOUR faces, 0.3 (1 + 0.1 s_i), s_i = +1
for i mod 4 in {0, 1} and -1 otherwise (faces i = 1..40), through two env files alternated face by face in bc.txt
(env_hi.dat, env_lo.dat). In the oxidation plateau mdot_ch is proportional to rho_e u_e C_H0, so the pattern reaches
the recession rate linearly; the node average of section 2.3 step 1 turns it into a period-4 NODE mode (factor
cos(pi/4)), on which the 5-point average has transfer (1 + 2 cos(pi/2) + 2 cos(pi))/5 = -1/5: the mode of the
width-5 run is 5 times smaller (verify.py asks >= 4.5). A face checkerboard would not do: the node average maps it to
exactly zero.

w5_2blk/ is w5/ cut into two blocks of 20 x 20 cells joined by 101 faces at x = 0.1 m: the receding surface then
spans two blocks, and the smoothing windows of the nodes beside the seam must cross it (plan 08 section 2.6, through
the surface-node map). verify.py compares its surface with w5's.

Run from this directory; it rewrites w1/, w5/ and w5_2blk/.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.abspath(os.path.join(HERE, "..", "..", "tools"))
sys.path.insert(0, TOOLS)
import make_darcy_case as mdc  # noqa: E402

TABLES = os.path.abspath(os.path.join(HERE, "..", "..", "darcy", "ATC2-chemistryOff-type2", "INPUT"))
BPRIME = os.path.abspath(os.path.join(HERE, "..", "tables", "bprime_tacot_earth.dat"))
FUSS_SH = os.path.abspath(os.path.join(HERE, "..", "ATC22", "FUSS.sh"))
NX, NY, LX, LY, DZ = 40, 20, 0.2, 0.05, 1.0e-3
T0 = 300.0
ENV_HEAD = "// t p_w rhoeUeCH0 h_r q_rad chem hconv T_edge   (SI; plan 08 section 2.1, linear in t, clamped)"


def env_rows(fac):
    return [(0.0, 101325.0, 0.003 * fac, 0.0, 0.0, 1.0, 0.0, 300.0),
            (0.1, 101325.0, 0.3 * fac, 1.5e6, 0.0, 1.0, 0.0, 300.0),
            (60.0, 101325.0, 0.3 * fac, 1.5e6, 0.0, 1.0, 0.0, 300.0),
            (60.1, 101325.0, 0.003 * fac, 0.0, 0.0, 0.0, 0.0, 300.0),
            (120.0, 101325.0, 0.003 * fac, 0.0, 0.0, 0.0, 0.0, 300.0)]


INI = """; =============================================================================
;  Wall smoothing (plan 08 sections 2.6, 3.6): a 2-D TACOT slab, 40 x 20 cells, the top face an ablating wall BC 306
;  whose rhoeUeCH0 varies with period four faces (env_hi.dat, env_lo.dat), law = nodeshift, 20 s; smoothing-width %(w)d.
;
;  Generated by ../generate.py -- edit that, not this.
; =============================================================================

[FUSS-Parameters]
newrun = true
res-threshold = 1e-30
time-threshold = 20.0
iter-threshold = 100000000

[FUSS-Numerics]
time-scheme = RK3
vnn = 0.5
time-accurate = true
integration-variables = cons
irs = false

[FUSS-Pyrolysis]
gas-closure = type2

[FUSS-Darcy]
solver = tridiag
p-init = 101325.0
p-wall = 101325.0

[FUSS-MeshMotion]
law = nodeshift

[FUSS-Ablation]
smoothing-width = %(w)d

[FUSS-IO]
sol-dtime     = 5.0
sol-overwrite = true
sol-format    = tecplot ascii
ini-diter     = 100000000
"""


def main():
    xs = [LX * i / NX for i in range(NX + 1)]
    ys = [LY * j / NY for j in range(NY + 1)]
    zs = [0.0, DZ]

    def top(i, j, k):
        s = 1 if (i % 4) in (0, 1) else -1
        return 306, "     0.5, 300.0, bprime_tacot_earth.dat, %s" % ("env_hi.dat" if s > 0 else "env_lo.dat")

    spec = {1: lambda i, j, k: (300, None), 2: lambda i, j, k: (300, None),
            3: lambda i, j, k: (301, "     0.000000E+00,"), 4: top,
            5: lambda i, j, k: (0, None), 6: lambda i, j, k: (0, None)}
    for w in (1, 5):
        d = os.path.join(HERE, "w%d" % w)
        if os.path.isdir(d):
            shutil.rmtree(d)
        os.makedirs(os.path.join(d, "INPUT"))
        os.makedirs(os.path.join(d, "MESH"))
        mdc.write_ic(os.path.join(d, "MESH", "mesh.tec"), xs, ys, zs, "Block1", False, T0)
        mdc.write_ic(os.path.join(d, "INPUT", "ic.tec"), xs, ys, zs, "Block1", True, T0)
        n = mdc.write_bc(os.path.join(d, "INPUT", "bc.txt"), NX, NY, spec)
        for f in ("virgin.dat", "char.dat", "gas.dat", "pyrolysis.dat", "phase.txt", "properties.dat"):
            shutil.copy(os.path.join(TABLES, f), os.path.join(d, "INPUT", f))
        shutil.copy(BPRIME, os.path.join(d, "INPUT", "bprime_tacot_earth.dat"))
        for name, fac in (("env_hi.dat", 1.1), ("env_lo.dat", 0.9)):
            with open(os.path.join(d, "INPUT", name), "w") as fh:
                fh.write(ENV_HEAD + "\n")
                for r in env_rows(fac):
                    fh.write(" ".join(repr(float(v)) for v in r) + "\n")
        open(os.path.join(d, "input.ini"), "w").write(INI % {"w": w})
        sh = open(FUSS_SH).read()
        assert "MASTERDIR=../../../.." in sh
        open(os.path.join(d, "FUSS.sh"), "w").write(sh.replace("MASTERDIR=../../../..", "MASTERDIR=../../../../..", 1))
        os.chmod(os.path.join(d, "FUSS.sh"), 0o755)
        open(os.path.join(d, ".slow"), "w").close()       # measured by gate_ablation_smoothing, not the regression
        print("smoothing: w%d/ written (%d bc records)" % (w, n))
    two_blocks(xs, ys, zs, top)


def write_zones(path, zones, with_vars):
    """A tecplot ASCII file of several blocks (zones), the format of make_darcy_case.write_ic."""
    lines = [' VARIABLES ="x" "y" "z" T matID' if with_vars else ' VARIABLES ="x" "y" "z"']
    for n, (xs, ys, zs) in enumerate(zones):
        ni, nj, nk = len(xs), len(ys), len(zs)
        varloc = "VARLOCATION=([1-3]=NODAL,[4-5]=CELLCENTERED)" if with_vars else "VARLOCATION=([1-3]=NODAL)"
        lines.append(" ZONE  T = Block%d, I=%d, J=%d, K=%d, DATAPACKING=BLOCK, %s,"
                     " SOLUTIONTIME=0.000000000000000E+000, STRANDID = 0" % (n + 1, ni, nj, nk, varloc))
        for axis in range(3):
            for k in range(nk):
                for j in range(nj):
                    for i in range(ni):
                        lines.append(mdc.fmt((xs[i], ys[j], zs[k])[axis]))
        if with_vars:
            nc = (ni - 1) * (nj - 1) * (nk - 1)
            lines.extend([mdc.fmt(T0)] * nc + [mdc.fmt(1.0)] * nc)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def two_blocks(xs, ys, zs, top):
    """w5_2blk/: blocks 1 (x 0..0.1) and 2 (x 0.1..0.2), 20 x 20 cells each, joined by 101 faces."""
    d = os.path.join(HERE, "w5_2blk")
    if os.path.isdir(d):                                   # rewritten whole, as w1/ and w5/: a kept copy would keep
        shutil.rmtree(d)                                   # an old input.ini or INPUT/ beside the new w5/
    shutil.copytree(os.path.join(HERE, "w5"), d)
    half = NX // 2
    zones = [(xs[:half + 1], ys, zs), (xs[half:], ys, zs)]
    write_zones(os.path.join(d, "MESH", "mesh.tec"), zones, False)
    write_zones(os.path.join(d, "INPUT", "ic.tec"), zones, True)
    out = []

    def rec(b, i, j, f, typ, line=None):
        out.append("%8d%8d%8d%8d%8d%8d" % (b, i, j, 1, f, typ))
        if line is not None:
            out.append(line)
    for b in (1, 2):
        for j in range(1, NY + 1):                         # face 1
            if b == 1:
                rec(b, 1, j, 1, 300)
            else:
                rec(b, 1, j, 1, 101, "%8d%8d%8d%8d%8d%8d%8d%8d%8d" % (1, half, j, 1, 2, 1, 0, 0, 1))
        for j in range(1, NY + 1):                         # face 2
            if b == 1:
                rec(b, half, j, 2, 101, "%8d%8d%8d%8d%8d%8d%8d%8d%8d" % (2, 1, j, 1, 1, 1, 0, 0, 1))
            else:
                rec(b, half, j, 2, 300)
        for i in range(1, half + 1):                       # face 3
            rec(b, i, 1, 3, 301, "     0.000000E+00,")
        for i in range(1, half + 1):                       # face 4: the pattern by the GLOBAL face index
            typ, line = top((b - 1) * half + i, NY, 1)
            rec(b, i, NY, 4, typ, line)
        for f in (5, 6):
            for j in range(1, NY + 1):
                for i in range(1, half + 1):
                    rec(b, i, j, f, 0)
    with open(os.path.join(d, "INPUT", "bc.txt"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    ini = open(os.path.join(d, "input.ini")).read()
    ini = ini.replace("smoothing-width %(w)d." % {"w": 5}, "smoothing-width 5, two blocks.")
    open(os.path.join(d, "input.ini"), "w").write(ini)
    print("smoothing: w5_2blk/ written (two blocks of %d x %d cells)" % (half, NY))


if __name__ == "__main__":
    main()
