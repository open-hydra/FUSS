#!/usr/bin/env python3
"""
Generate R5's type-2 variant (plan 08 section 2.9 (3), stage D): pyrolysis under the type-2 gas closure on the
two-block receding mesh of ../conjugate_receding, so that the conduction, the gas mass and the gas enthalpy all
cross the unequal-spacing 101 interface (dx2/dx1 = 4).

From ../conjugate_receding: its mesh, its bc.txt (block 1: the receding 306 face 1, the 101 face 2; block 2: the 101
face 1, a 302 face 2; 301 walls; null k faces) and its env file, but TACOT in both blocks (matID 1: the tables of
../../pyrolysis/darcy/ATC2-chemistryOff-type2), T(0) = 300 K, and the 306 face heated through its chemistry-off env rows
(hconv 1000 W/m2/K toward T_edge 1000 K): the slab decomposes near the receding face and its gas pressure reaches the
interface. [FUSS-Pyrolysis] gas-closure = type2 (tridiag along x, the open 306 face's direction), law = nodeshift,
sdot-override = 1e-5 m/s, dump-interface-flux = true, 200 steps. verify.py pairs, face by face, the conduction q_if,
the gas mass flow qm_if and the gas enthalpy flow qh_if of the two sides of every 101 face.

Run from this directory; it rewrites INPUT/, MESH/, input.ini and FUSS.sh.
"""
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
R5 = os.path.abspath(os.path.join(HERE, "..", "conjugate_receding"))
TABLES = os.path.abspath(os.path.join(HERE, "..", "..", "pyrolysis", "darcy", "ATC2-chemistryOff-type2", "INPUT"))

INI = """; =============================================================================
;  R5's type-2 variant (plan 08 section 2.9 (3), stage D): the receding two-block conjugate slab of
;  ../conjugate_receding with TACOT under the type-2 gas closure. The 306 face is heated (chemistry off, hconv 1000
;  toward 1000 K) and recedes at the TEST ONLY sdot-override of 1e-5 m/s (law nodeshift). Oracle: the two sides of
;  every 101 face carry opposite conduction, gas mass and gas enthalpy flows (interface-flux.txt, verify.py).
;
;  Generated by generate.py -- edit that, not this.
; =============================================================================

[FUSS-Parameters]
newrun = true
res-threshold = 1e-30
time-threshold = 1.0e6
iter-threshold = 200

[FUSS-Numerics]
time-scheme = RK3
vnn = 0.5
time-accurate = true
integration-variables = cons
irs = false

[FUSS-Pyrolysis]
gas-closure = type2

[FUSS-Darcy]
solver = tridiag
p-init = 101325.0
p-wall = 101325.0

[FUSS-MeshMotion]
law = nodeshift

[FUSS-Ablation]
sdot-override = 1e-05
dump-interface-flux = true

[FUSS-IO]
sol-diter     = 50
sol-overwrite = true
sol-format    = tecplot ascii
ini-diter     = 100000
"""


def main():
    for d in ("INPUT", "MESH"):
        if os.path.isdir(os.path.join(HERE, d)):
            shutil.rmtree(os.path.join(HERE, d))
    shutil.copytree(os.path.join(R5, "MESH"), os.path.join(HERE, "MESH"))
    os.makedirs(os.path.join(HERE, "INPUT"))
    for f in ("bc.txt", "env_r5.dat"):
        shutil.copy(os.path.join(R5, "INPUT", f), os.path.join(HERE, "INPUT", f))
    for f in ("virgin.dat", "char.dat", "gas.dat", "pyrolysis.dat", "phase.txt", "properties.dat"):
        shutil.copy(os.path.join(TABLES, f), os.path.join(HERE, "INPUT", f))
    # ic.tec: every zone's T block to 300 K and matID block to 1 (the cell-centred blocks after the nodal ones)
    lines = open(os.path.join(R5, "INPUT", "ic.tec")).read().split("\n")
    out, i = [], 0
    while i < len(lines):
        out.append(lines[i])
        m = re.search(r"ZONE.*I=(\d+), J=(\d+), K=(\d+)", lines[i])
        if m:
            I, J, K = (int(x) for x in m.groups())
            nn, nc = I * J * K, (I - 1) * (J - 1) * max(K - 1, 1)
            out.extend(lines[i + 1:i + 1 + 3 * nn])
            out.extend([" 3.000000000000000E+02"] * nc)
            out.extend([" 1.000000000000000E+00"] * nc)
            i += 1 + 3 * nn + 2 * nc
            continue
        i += 1
    open(os.path.join(HERE, "INPUT", "ic.tec"), "w").write("\n".join(out))
    open(os.path.join(HERE, "input.ini"), "w").write(INI)
    shutil.copy(os.path.join(R5, "FUSS.sh"), os.path.join(HERE, "FUSS.sh"))
    print("conjugate_receding_t2 written")


if __name__ == "__main__":
    main()
